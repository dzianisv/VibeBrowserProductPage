#!/usr/bin/env node
/**
 * Generates shared/blog/posts.generated.ts — every blog/*.md file inlined as
 * a string map.
 *
 * Why: the blog repository (shared/blog/repository.ts) reads posts from the
 * filesystem at request time. That works on Node/Vercel but not on
 * Cloudflare Workers, which has no filesystem — there the repository falls
 * back to this bundled map. The Cloudflare deploy workflow re-runs this
 * script before every build, so the deployed site is always current; the
 * committed copy only exists so other builds (which use the fs path) keep
 * compiling and never read stale data.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const blogDir = path.join(root, 'blog')
const outPath = path.join(root, 'shared', 'blog', 'posts.generated.ts')

const files = fs
  .readdirSync(blogDir)
  .filter((f) => f.endsWith('.md'))
  .sort()

const map = {}
for (const f of files) {
  map[f] = fs.readFileSync(path.join(blogDir, f), 'utf8')
}

const out = `// GENERATED by scripts/generate-blog-content.mjs from blog/*.md — do not edit by hand.
// Regenerated by the Cloudflare deploy workflow before every build; the committed
// copy exists so non-Cloudflare builds keep compiling (they read posts from disk).
export const BLOG_POST_FILES: Record<string, string> = ${JSON.stringify(map, null, 2)}
`

fs.writeFileSync(outPath, out)
console.log(`posts.generated.ts written: ${files.length} posts`)
